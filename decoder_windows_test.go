func fixtureBytes(t *testing.T, name string) []byte {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func test7ZipVolumes(t *testing.T) [][]byte {
	data := fixtureBytes(t, "encrypted-inner.7z")
	return [][]byte{data[:120], data[120:240], data[240:]}
}

func TestOpeningSelected7ZipVolumes(t *testing.T) {
	work := t.TempDir()
	t.Setenv("LOCALAPPDATA", work)
	volumes := test7ZipVolumes(t)
	paths := make([]string, 0, len(volumes))
	for index, data := range volumes {
		path := filepath.Join(work, fmt.Sprintf("资料卷.7Z.%03d", index+1))
		if err := os.WriteFile(path, data, 0600); err != nil {
			t.Fatal(err)
		}
		paths = append(paths, path)
	}
	ui := &recursiveTestUI{reply: passwordReply{Value: "nestedunpack-regression-only"}}
	if summary := executeNested(context.Background(), []string{paths[2], paths[0], paths[1]}, ui); summary != (batchSummary{Total: 1, Success: 1}) {
		t.Fatalf("opening direct volumes: %+v (%s)", summary, ui.result.Message)
	}
	if ui.result.Output != filepath.Join(work, "资料卷-解压") || ui.result.Structure.Format != "7z 分卷" || len(ui.result.Structure.Volumes) != len(volumes) {
		t.Fatalf("unexpected split volume result: %+v / %+v", ui.result, ui.result.Structure)
	}
	for _, path := range paths {
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("source volume missing: %v", err)
		}
	}
	if data, err := os.ReadFile(filepath.Join(ui.result.Output, "media", "detail.txt")); err != nil || !bytes.Equal(data, bytes.Repeat([]byte("nested media payload\n"), 600)) {
		t.Fatalf("split volume contents differed: %v", err)
	}
}

func TestExtractWinZipAESFromMedia(t *testing.T) {
	outerPrefix := []byte{0, 0, 0, 24, 'f', 't', 'y', 'p', 'm', 'p', '4', '2'}
	want := bytes.Repeat([]byte("NestedUnpack AES regression fixture.\n"), 40)
	for _, fixture := range []struct {
		name string
		ae1  bool
	}{{"aes256.zip", false}, {"aes128-store.zip", true}} {
		t.Run(fixture.name, func(t *testing.T) {
			work := t.TempDir()
			t.Setenv("LOCALAPPDATA", work)
			archive := fixtureBytes(t, fixture.name)
			if fixture.ae1 {
				archive = testZIPWithCRC(t, archive, crc32.ChecksumIEEE(want))
			}
			path := filepath.Join(work, "加密.mp4")
			if err := os.WriteFile(path, append(append([]byte(nil), outerPrefix...), archive...), 0600); err != nil {
				t.Fatal(err)
			}
			ui := &recursiveTestUI{reply: passwordReply{Value: "nestedunpack-regression-only"}}
			if summary := executeNested(context.Background(), []string{path}, ui); summary.Success != 1 || ui.prompts != 2 {
				t.Fatalf("opening AES ZIP: %+v (%s) with %d prompts", summary, ui.result.Message, ui.prompts)
			}
			data, err := os.ReadFile(filepath.Join(ui.result.Output, "message.txt"))
			if err != nil || !bytes.Equal(data, want) {
				t.Fatalf("AES ZIP contents differed: %v", err)
			}
		})
	}
}

// AE-1 keeps the CRC in the ZIP headers. Its encrypted payload is identical
// to AE-2, so use ciphertext generated by 7-Zip for both test variants.
func testZIPWithCRC(t *testing.T, data []byte, crc uint32) []byte {
	t.Helper()
	archive, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil || len(archive.File) != 1 {
		t.Fatalf("invalid WinZip AES fixture: %v", err)
	}
	member := archive.File[0]
	for extra := member.Extra; len(extra) >= 4; {
		length := int(le.Uint16(extra[2:]))
		if le.Uint16(extra) == zipAESExtra {
			le.PutUint16(extra[4:], 1)
			break
		}
		extra = extra[4+length:]
	}
	member.CRC32 = crc
	var output bytes.Buffer
	writer := zip.NewWriter(&output)
	if err := writer.Copy(member); err != nil {
		t.Fatal(err)
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	return output.Bytes()
}

func TestExtractRAR(t *testing.T) {
	for _, fixture := range []struct {
		name     string
		password string
	}{{"rar3-solid.rar", ""}, {"rar5-solid.rar", ""}, {"rar5-psw.rar", "password"}, {"rar5-hpsw.rar", "password"}} {
		t.Run(fixture.name, func(t *testing.T) {
			work := t.TempDir()
			t.Setenv("LOCALAPPDATA", work)
			path := filepath.Join(work, fixture.name)
			if err := os.WriteFile(path, fixtureBytes(t, fixture.name), 0600); err != nil {
				t.Fatal(err)
			}
			ui := &recursiveTestUI{reply: passwordReply{Value: fixture.password}}
			wantPrompts := 0
			if fixture.password != "" {
				wantPrompts = 2
			}
			if summary := executeNested(context.Background(), []string{path}, ui); summary.Success != 1 || ui.prompts != wantPrompts {
				t.Fatalf("opening RAR: %+v (%s) with %d prompts", summary, ui.result.Message, ui.prompts)
			}
			for _, file := range []string{"stest1.txt", "stest2.txt"} {
				data, err := os.ReadFile(filepath.Join(ui.result.Output, file))
				if err != nil || crc32.ChecksumIEEE(data) != 0xc5b7e6a2 {
					t.Fatalf("RAR member contents differed: %s (%v)", file, err)
				}
			}
		})
	}
}

func TestRejectRARHardLinks(t *testing.T) {
	work := t.TempDir()
	t.Setenv("LOCALAPPDATA", work)
	path := filepath.Join(work, "link.rar")
	if err := os.WriteFile(path, fixtureBytes(t, "rar5-hlink.rar"), 0600); err != nil {
		t.Fatal(err)
	}
	ui := &recursiveTestUI{}
	summary := executeNested(context.Background(), []string{path}, ui)
	if summary.Failed != 1 || ui.result.Output != "" || !strings.Contains(ui.result.Message, "不支持的压缩包成员") {
		t.Fatalf("RAR should reject hard links: %+v (%s)", summary, ui.result.Message)
	}
}
